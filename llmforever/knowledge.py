DOMAINS = {
    "self": _SELF,
    "daily": _DAILY,
    "math": _MATH,
    "cs": _CS,
}


def _build() -> List[Tuple[str, Tuple[str, ...], str]]:
    entries: List[Tuple[str, Tuple[str, ...], str]] = []
    for domain, rows in DOMAINS.items():
        for keys, answer in rows:
            parts = tuple(part.strip() for part in keys.split("|") if part.strip())
            if parts:
                entries.append((domain, parts, answer))
    return entries


_ENTRIES = _build()
SIZE = len(_ENTRIES)


def _bigrams(text: str) -> set:
    cleaned = _PUNCT_RE.sub("", text.lower())
    return {cleaned[i : i + 2] for i in range(len(cleaned) - 1)}


def _score(query: str, query_grams: set, keys: Tuple[str, ...]) -> float:
    score = 0.0
    for key in keys:
        if key in query:
            score += 5.0 + min(len(key), 8) * 1.2
    key_grams = _bigrams("".join(keys))
    if query_grams and key_grams:
        overlap = len(query_grams & key_grams)
        score += 8.0 * overlap / max(1, len(query_grams))
        if overlap >= 2 and overlap / max(1, len(query_grams)) >= 0.5:
            score += 3.0
    return score


def best_match(text: str) -> Tuple[float, Optional[Tuple[str, Tuple[str, ...], str]]]:
    """返回 (最高分, 命中的条目)。没有条目时返回 (0.0, None)。"""
    query = (text or "").strip().lower()
    if not query:
        return 0.0, None
    grams = _bigrams(query)
    best_score = 0.0
    best_entry = None
    for entry in _ENTRIES:
        score = _score(query, grams, entry[1])
        if score > best_score:
            best_score = score
            best_entry = entry
    return best_score, best_entry


def lookup(text: str) -> Optional[Tuple[str, Tuple[str, ...], str]]:
    score, entry = best_match(text)
    if entry is None or score < THRESHOLD:
        return None
    return entry


def render(entry: Tuple[str, Tuple[str, ...], str], stats: Dict[str, object]) -> str:
    answer = entry[2]
    for key, value in stats.items():
        answer = answer.replace("{" + key + "}", str(value))
    return answer
